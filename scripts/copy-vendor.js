// Copies the browser libraries into public/vendor so the app runs fully offline,
// and bundles the Lucide icons the app uses into public/vendor/icons.js.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const out = path.join(root, 'public', 'vendor');
fs.mkdirSync(out, { recursive: true });

const files = [
  ['node_modules/xlsx/dist/xlsx.full.min.js', 'xlsx.full.min.js'],
  ['node_modules/chart.js/dist/chart.umd.js', 'chart.umd.js'],
];
for (const [src, dst] of files) {
  const from = path.join(root, src);
  if (!fs.existsSync(from)) { console.warn('missing', src); continue; }
  fs.copyFileSync(from, path.join(out, dst));
  console.log('vendor:', dst);
}

// Only the icons the interface uses (Lucide, ISC licence).
const ICONS = [
  'layout-dashboard', 'upload', 'house', 'file-spreadsheet', 'search', 'refresh-cw', 'sun', 'moon',
  'panel-left-close', 'panel-left-open', 'menu', 'x', 'chevron-right', 'chevron-down', 'chevron-left',
  'triangle-alert', 'octagon-alert', 'info', 'lightbulb', 'circle-check', 'download', 'layout-grid',
  'table-2', 'arrow-up-right', 'eye', 'list-filter', 'filter-x', 'calendar', 'user', 'package', 'hash',
  'indian-rupee', 'boxes', 'file-text', 'folder-open', 'replace', 'trash-2', 'sparkles', 'target',
  'trending-up', 'trending-down', 'chart-column', 'arrow-left', 'locate', 'pen-line', 'badge-check',
  'cloud', 'wrench', 'files', 'activity', 'rows-3', 'circle-help', 'tag',
];
const dir = path.join(root, 'node_modules', 'lucide-static', 'icons');
const map = {};
for (const name of ICONS) {
  const f = path.join(dir, name + '.svg');
  if (!fs.existsSync(f)) { console.warn('missing icon', name); continue; }
  const svg = fs.readFileSync(f, 'utf8');
  map[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}
const js = `// Generated by scripts/copy-vendor.js from lucide-static (ISC licence). Do not edit.
window.ICONS = ${JSON.stringify(map)};
window.icon = function (name, cls) {
  var body = window.ICONS[name] || '';
  return '<svg class="ic' + (cls ? ' ' + cls : '') + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + body + '</svg>';
};
`;
fs.writeFileSync(path.join(out, 'icons.js'), js);
console.log('vendor: icons.js (' + Object.keys(map).length + ' icons)');
